#!/usr/bin/env python3
import argparse
import json
from datetime import datetime, timezone
from pathlib import Path


def load_reports(root: Path):
    cases = []
    for p in sorted(root.rglob("*.json")):
        try:
            data = json.loads(p.read_text(encoding="utf-8-sig"))
        except Exception:
            continue
        if {"db_pair", "atomic_level", "mode", "row_count"}.issubset(data):
            cases.append(data)
    cases.sort(key=lambda x: (x["db_pair"], x["atomic_level"], int(x["row_count"])))
    return cases


def fmt_rows(n):
    n = int(n)
    if n >= 1_000_000:
        return f"{n/1_000_000:g}M"
    if n >= 1_000:
        return f"{n/1_000:g}k"
    return str(n)


def transaction_groups(case):
    rows = int(case.get("row_count") or 0)
    batch = int(case.get("batch_size") or 0)
    if case.get("atomic_level") == "JOB":
        return 1
    if batch <= 0:
        return None
    return (rows + batch - 1) // batch


def render(cases, lang):
    zh = lang == "zh"
    title = "## 深度資料量 Benchmark" if zh else "## Deep Data-Volume Benchmark"
    note = (
        "此表由排程／手動 deep benchmark 產生；屬 GitHub-hosted runner regression data，不是 production capacity claim。"
        if zh else
        "Generated by the scheduled/manual deep benchmark on GitHub-hosted runners; this is regression data, not a production-capacity claim."
    )
    if not cases:
        pending = "尚未產生 deep benchmark 結果。" if zh else "Deep benchmark results have not been generated yet."
        return f"{title}\n\n{pending}\n"
    batch_label = "每批筆數" if zh else "Batch"
    groups_label = "交易群組" if zh else "Txn groups"
    lines = [
        title, "", note, "",
        f"| DB | Atomic | Rows | {batch_label} | {groups_label} | Duration | Rows/s | Status |",
        "|---|---|---:|---:|---:|---:|---:|---|",
    ]
    for c in cases:
        duration = c.get("duration_ms")
        rps = c.get("rows_per_second")
        batch = int(c.get("batch_size") or 0)
        groups = transaction_groups(c)
        dur = "-" if duration is None else f"{duration/1000:.2f}s"
        rps_text = "-" if rps is None else f"{rps:,.1f}"
        batch_text = "-" if batch <= 0 else f"{batch:,}"
        groups_text = "-" if groups is None else f"{groups:,}"
        lines.append(
            f"| {c['db_pair']} | {c['atomic_level']} | {fmt_rows(c['row_count'])} | "
            f"{batch_text} | {groups_text} | {dur} | {rps_text} | {str(c.get('status','')).upper()} |"
        )
    return "\n".join(lines) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--reports-dir", required=True)
    ap.add_argument("--results", required=True)
    ap.add_argument("--run-url", required=True)
    ap.add_argument("--commit-sha", required=True)
    args = ap.parse_args()

    cases = load_reports(Path(args.reports_dir))
    now = datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")
    result = {
        "updated_at": now,
        "run_url": args.run_url,
        "commit_sha": args.commit_sha,
        "case_count": len(cases),
        "cases": cases,
    }
    out = Path(args.results)
    out.write_text(json.dumps(result, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    gen = out.parent / "_generated"
    gen.mkdir(parents=True, exist_ok=True)
    (gen / "deep-performance-results-en.md").write_text(render(cases, "en"), encoding="utf-8")
    (gen / "deep-performance-results-zh.md").write_text(render(cases, "zh"), encoding="utf-8")


if __name__ == "__main__":
    main()
